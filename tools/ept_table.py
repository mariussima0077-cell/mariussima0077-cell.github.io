#!/usr/bin/env python3
"""v16-157: writes server/ept.js = enemy power of every campaign stage (normal + hard), used by Torque Guard
to check the battle receipts. Run again when monsters / stage strength change: python3 tools/ept_table.py"""
import asyncio, json, os, re, shutil, subprocess, sys, tempfile, time, socket
REPO=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tmp=tempfile.mkdtemp(); root=os.path.join(tmp,'site')
shutil.copytree(REPO, root, ignore=shutil.ignore_patterns('.git','store','server'))
p=os.path.join(root,'secure.js'); s=open(p).read()
s=re.sub(r'^const TEST_MODE = .*$','const TEST_MODE = true;',s,flags=re.M)
s=re.sub(r'^const TEST_ACC = .*$','const TEST_ACC = true;',s,flags=re.M); open(p,'w').write(s)
p=os.path.join(root,'battle.js'); s=open(p).read()
k='if(window.SEC&&SEC.TEST_MODE)window.__DEV='
s=s.replace(k,'window.__EPX={ep:(i,h)=>{const o=HM;HM=h;const r=enemyPower(i);HM=o;return r;},N:NST,tp:ids=>teamPower(ids.map(heroOf)),mechs:()=>myMechs().map(h=>({id:h.id,p:pow(h)})),sim:(i,ids,h)=>{const o=HM;HM=h;window.__SIM=1;try{return simRun(i,ids.map(heroOf),600);}finally{window.__SIM=0;HM=o;}}};\n'+k,1)
open(p,'w').write(s)
sock=socket.socket();sock.bind(('',0));port=sock.getsockname()[1];sock.close()
srv=subprocess.Popen([sys.executable,'-m','http.server',str(port)],cwd=root,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL);time.sleep(1)
async def main():
  from playwright.async_api import async_playwright
  async with async_playwright() as pw:
    b=await pw.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=await (await b.new_context(viewport={'width':360,'height':800},service_workers='block')).new_page()
    await pg.goto(f'http://127.0.0.1:{port}/')
    for _ in range(120):
      try:
        if await pg.evaluate("!!window.__EPX && document.getElementById('loader').classList.contains('hide')"): break
        await pg.mouse.click(180,720)
      except Exception as e: pass
      await pg.wait_for_timeout(500)
    await pg.wait_for_timeout(1500)
    N=await pg.evaluate('__EPX.N'); print('N',N)
    tab=await pg.evaluate('[0,1].map(h=>[...Array(__EPX.N)].map((_,i)=>__EPX.ep(i,h)))')
    from math import log10,floor
    r=lambda x:int(x) if x<1000 else int(round(x/10**(floor(log10(x))-2))*10**(floor(log10(x))-2))
    n,h=[[r(x) for x in t] for t in tab]
    open(os.path.join(REPO,'server','ept.js'),'w').write('// v16-157 (generated by tools/ept_table.py from battle.js – do not edit by hand): enemy power of every campaign stage\n// EP_N = normal, EP_H = hard. Rounded to 3 digits. Re-generate when monsters / stage strength change.\nexport const EP_N='+json.dumps(n,separators=(',',':'))+';\nexport const EP_H='+json.dumps(h,separators=(',',':'))+';\n')
    print('server/ept.js written')
    await b.close()
try: asyncio.run(main())
finally: srv.terminate(); shutil.rmtree(tmp,ignore_errors=True)
